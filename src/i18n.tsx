const dict: Record<Lang, Record<Key, string>> = { it, en }

export type T = (key: Key, vars?: Record<string, string | number>) => string

const I18nCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T }>(null!)

export function I18nProvider({ children }: { children: ReactNode }) {
  const initial: Lang = navigator.language?.toLowerCase().startsWith('it') ? 'it' : 'en'
  const [lang, setLang] = useStoredState<Lang>('cc.lang', initial)
  const t: T = (key, vars) => {
    // a count of one uses the key's ".one" form when there is one: "1 partita", not "1 partite"
    const one = vars && Number(vars.n) === 1 ? dict[lang][`${key}.one` as Key] : undefined
    let s = one ?? dict[lang][key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
  document.documentElement.lang = lang
  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>
}

export const useI18n = () => useContext(I18nCtx)
